// Helper functions for easy access
export function getAllCourses(): Course[] {
  return COURSES_CATALOG;
}

export function getCourseById(id: string): Course | undefined {
  return COURSES_CATALOG.find((c) => c.id === id);
}

export function getCoursesByCategory(category: CourseCategory): Course[] {
  return COURSES_CATALOG.filter((c) => c.category === category);
}

/**
 * Finds recommended courses based on student skill gaps.
 */
export function getRecommendedCoursesForSkills(missingSkillNames: string[]): Course[] {
  const normalizedMissing = missingSkillNames.map((s) => s.toLowerCase().trim());
  
  const matches = COURSES_CATALOG.filter((course) => {
    return course.skills.some((skill) =>
      normalizedMissing.some(
        (missing) =>
          skill.toLowerCase().includes(missing) || missing.includes(skill.toLowerCase())
      )
    );
  });

  // Sort by number of matching skills (descending)
  matches.sort((a, b) => {
    const aCount = a.skills.filter((s) =>
      normalizedMissing.some((m) => s.toLowerCase().includes(m) || m.includes(s.toLowerCase()))
    ).length;
    const bCount = b.skills.filter((s) =>
      normalizedMissing.some((m) => s.toLowerCase().includes(m) || m.includes(s.toLowerCase()))
    ).length;
    return bCount - aCount;
  });

  return matches;
}
